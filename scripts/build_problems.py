def normalize(text: str) -> str:
    """Strip trailing whitespace from each line and from the payload as a whole.

    Parameters
    ----------
    text : str
        Raw stdin payload or program output.

    Returns
    -------
    str
        Text with per-line and trailing whitespace removed.
    """
    return "\n".join(line.rstrip() for line in text.rstrip().split("\n"))


def load_module(path: Path) -> ModuleType:
    """Import a problem module from its file path.

    Parameters
    ----------
    path : Path
        Path to the module file.

    Returns
    -------
    ModuleType
        The imported module.

    Raises
    ------
    ImportError
        If the module cannot be loaded from the path.
    """
    spec = importlib.util.spec_from_file_location(path.stem, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[path.stem] = module
    spec.loader.exec_module(module)
    return module


def build_test_cases(
    title: str, inputs: list[str], solve: Callable[[str], str], brute: Callable[[str], str] | None
) -> list[dict[str, str]]:
    """Run the reference solution over every input to produce expected outputs.

    Parameters
    ----------
    title : str
        Problem title, used in error messages.
    inputs : list[str]
        Stdin payloads.
    solve : Callable[[str], str]
        Reference solution.
    brute : Callable[[str], str] | None
        Independent implementation cross-checked against solve.

    Returns
    -------
    list[dict[str, str]]
        Test cases with input and expected output.

    Raises
    ------
    ValueError
        If a solver is nondeterministic, disagrees with brute, or emits nothing.
    """
    cases: list[dict[str, str]] = []
    for payload in inputs:
        stdin_text = normalize(payload)
        expected = normalize(solve(stdin_text))
        if expected != normalize(solve(stdin_text)):
            raise ValueError(f"{title}: solve is nondeterministic on {stdin_text!r}")
        if not expected:
            raise ValueError(f"{title}: empty expected output on {stdin_text!r}")
        if brute is not None:
            from_brute = normalize(brute(stdin_text))
            if from_brute != expected:
                raise ValueError(
                    f"{title}: brute disagrees on {stdin_text!r}: "
                    f"solve={expected!r} brute={from_brute!r}"
                )
        cases.append({"input": stdin_text, "output": expected})
    return cases


def build_problem(spec: dict[str, Any], canonical: dict[str, str]) -> dict[str, Any]:
    """Validate one problem spec and turn it into a seedable document.

    Parameters
    ----------
    spec : dict[str, Any]
        Problem spec from a problemdata module.
    canonical : dict[str, str]
        Canonical title to level mapping for the owning module.

    Returns
    -------
    dict[str, Any]
        Document matching the Problem schema, minus the title index prefix.

    Raises
    ------
    ValueError
        If any field is missing, malformed, or off the canonical roster.
    """
    title = spec.get("title", "")
    if title not in canonical:
        raise ValueError(f"{title!r} is not on this module's roster")
    if spec.get("level") != canonical[title]:
        raise ValueError(f"{title}: level {spec.get('level')!r} != {canonical[title]!r}")

    for field in ("topics", "description", "examples", "constraints"):
        if not str(spec.get(field, "")).strip():
            raise ValueError(f"{title}: {field} is empty")

    inputs = spec.get("inputs") or []
    if len(inputs) < MIN_TEST_CASES:
        raise ValueError(f"{title}: {len(inputs)} inputs, need at least {MIN_TEST_CASES}")
    if len({normalize(payload) for payload in inputs}) != len(inputs):
        raise ValueError(f"{title}: duplicate inputs")

    solve = spec.get("solve")
    if not callable(solve):
        raise ValueError(f"{title}: solve is not callable")

    return {
        "title": title,
        "level": spec["level"],
        "topics": spec["topics"],
        "companies": spec.get("companies", ""),
        # The three markdown fields are concatenated before rendering, so each
        # needs a trailing blank line or paragraphs run together.
        "description": f"{spec['description'].rstrip()}\n\n",
        "examples": f"{spec['examples'].rstrip()}\n\n",
        "constraints": f"{spec['constraints'].rstrip()}\n\n",
        "testCases": build_test_cases(
            title,
            inputs,
            cast("Callable[[str], str]", solve),
            cast("Callable[[str], str] | None", spec.get("brute")),
        ),
    }


def main() -> int:
    """Build problems.json, reporting per-module failures and roster gaps.

    Returns
    -------
    int
        Process exit code: 0 when every requested module built cleanly.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", help="build a single problemdata module by name")
    args = parser.parse_args()

    wanted = [args.only] if args.only else list(GROUPS)
    problems: list[dict[str, Any]] = []
    failures: list[str] = []

    for module_name in wanted:
        if module_name not in GROUPS:
            failures.append(f"{module_name}: unknown module")
            continue
        canonical = dict(GROUPS[module_name])
        path = DATA_DIR / f"{module_name}.py"
        if not path.exists():
            failures.append(f"{module_name}: missing {path.name}")
            continue

        try:
            module = load_module(path)
            specs = module.PROBLEMS
        except Exception as error:  # noqa: BLE001 - report and keep building the rest
            failures.append(f"{module_name}: {error}")
            continue

        built: dict[str, dict[str, Any]] = {}
        for spec in specs:
            try:
                document = build_problem(spec, canonical)
            except Exception as error:  # noqa: BLE001 - one bad problem must not hide the rest
                failures.append(f"{module_name}: {error}")
                continue
            built[document["title"]] = document

        missing = [title for title in canonical if title not in built]
        if missing:
            failures.append(f"{module_name}: missing {len(missing)} - {', '.join(missing)}")

        # Emit in roster order so seeded problem numbers follow the study plan.
        problems.extend(built[title] for title in canonical if title in built)
        case_count = sum(len(built[title]["testCases"]) for title in built)
        print(f"{module_name}: {len(built)}/{len(canonical)} problems, {case_count} cases")

    for failure in failures:
        print(f"FAIL {failure}", file=sys.stderr)

    if args.only:
        print(f"built {len(problems)} problems (module {args.only}, json not written)")
        return 1 if failures else 0

    OUTPUT_PATH.write_text(json.dumps(problems, indent=2), encoding="utf-8")
    expected_total = sum(len(titles) for titles in GROUPS.values())
    print(f"wrote {OUTPUT_PATH.name}: {len(problems)}/{expected_total} problems")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
